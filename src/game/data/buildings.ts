import type { Season } from './calendar';

export type BuildingCategory =
  | 'fortification'
  | 'housing'
  | 'farming'
  | 'animals'
  | 'gathering'
  | 'industry'
  | 'trade'
  | 'military'
  | 'infrastructure'
  | 'civic';

